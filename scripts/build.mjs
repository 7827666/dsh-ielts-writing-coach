import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
if (args.some(arg => arg !== '--check')) {
  throw new Error('Usage: node scripts/build.mjs [--check]');
}
const check = args.includes('--check');
const source = (await readFile(join(root, 'skills/ielts-writing-coach/SKILL.md'), 'utf8'))
  .replaceAll('\r\n', '\n');
const headerEnd = source.indexOf('\n---\n', 4);
if (!source.startsWith('---\n') || headerEnd < 0) {
  throw new Error('SKILL.md must start with a closed YAML frontmatter block.');
}
const prompt = source.slice(headerEnd + 5).trim() + '\n';
if (!prompt.trim()) throw new Error('Refusing to build an empty coaching prompt.');
if (prompt.includes('{{')) {
  throw new Error('DSH persona interpolates {{...}}; remove literal template delimiters before building.');
}

const patch = [
  '# Generated by scripts/build.mjs from skills/ielts-writing-coach/SKILL.md.',
  '# This bundle only inserts its own Agent preset.',
  '- insert:',
  '    - id: preset-ielts-writing-coach',
  "      name: '@deepseek-ai/dsh-agent-preset'",
  '      config:',
  '        id: ielts-writing-coach',
  "        name: '雅思写作教练'",
  "        description: 'Academic · 7.5–8 分训练；先评分与分析，说“开始修改”后再改全文。'",
  '        order: 20',
  '        plugins:',
  '          - id: persona',
  "            name: '@deepseek-ai/dsh-persona'",
  '            config:',
  '              complete: true',
  '              includeRuntimeContext: false',
  '              prefix: |',
  ...prompt.trimEnd().split('\n').map(line => line ? `                ${line}` : ''),
  '          - id: tool-web',
  "            name: '@deepseek-ai/dsh-tool-web'",
  '            config:',
  '              search: true',
  '              fetch: true',
  '              searchTimeoutMs: 60000',
  '          - id: compaction',
  '            name: cordis:group',
  '            group: true',
  '            isolate:',
  '              compaction: true',
  '            config:',
  '              - id: compaction-basic',
  "                name: '@deepseek-ai/dsh-compaction-basic'",
  '              - id: command-compact',
  "                name: '@deepseek-ai/dsh-command-compact'",
  '',
].join('\n');

let stale = false;
for (const [relativePath, expected] of [
  ['prompts/ielts-writing-coach.md', prompt],
  ['cordis.patch.yml', patch],
]) {
  const path = join(root, relativePath);
  if (check) {
    const actual = await readFile(path, 'utf8').catch(error => {
      if (error.code === 'ENOENT') return undefined;
      throw error;
    });
    if (actual !== expected) {
      console.error(`Out of date or missing: ${relativePath}. Run npm run build.`);
      stale = true;
    }
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, expected, 'utf8');
    console.log(`Generated ${relativePath}`);
  }
}
if (stale) process.exitCode = 1;
else if (check) console.log('Prompt and DSH bundle match the canonical skill.');
